/*
 * Описания машин.
 *
 * Здесь собрана ВСЯ аппаратная специфика конкретного компьютера: карта памяти,
 * параметры экрана, раскладка клавиатуры. Код эмулятора (процессор, шина,
 * видео) ничего не знает про РК-86 — он работает с этим описанием.
 * Чтобы получить Микрошу или Апогей, достаточно добавить сюда новый объект.
 *
 * Тип области памяти (region.type):
 *   'ram' — обычное ОЗУ (чтение/запись)
 *   'rom' — ПЗУ (запись игнорируется, пишем предупреждение в консоль)
 *   'io'  — устройство; обращение транслируется в dev.read(off) / dev.write(off, v)
 *           off = (addr - start) & region.mask
 *   'none'— не подключено, чтение даёт 0xFF
 */
(function (global) {
  'use strict';

  /* --- Коды КОИ-7 Н2 -------------------------------------------------------
   * 0x20..0x5F — как в ASCII (заглавные латинские буквы, цифры, знаки),
   * 0x60..0x7F — кириллица в порядке ЮАБЦДЕФГХИЙКЛМНОПЯРСТУЖВЬЫЗШЭЩЧЪ.
   * Эта строка используется генератором знакогенератора по умолчанию.
   */
  const KOI7_CYRILLIC = 'ЮАБЦДЕФГХИЙКЛМНОПЯРСТУЖВЬЫЗШЭЩЧЪ';

  /* --- Управляющие коды РК-86 --------------------------------------------- */
  const KEY = {
    LEFT: 0x08,   // <-
    TAB: 0x09,
    DOWN: 0x1A,
    UP: 0x19,
    RIGHT: 0x18,
    LF: 0x0A,     // ПС (перевод строки)
    CR: 0x0D,     // ВК (возврат каретки)
    HOME: 0x0C,   // СТР (очистка экрана)
    RUB: 0x1F     // ЗБ (забой)
  };

  /* --- Матрица клавиатуры --------------------------------------------------
   * ВВ55 (i8255): PA — выход, выбор строки (активный уровень — НИЗКИЙ),
   *               PB — вход, чтение столбцов (нажатие = 0),
   *               PC(младшие биты) — вход, модификаторы УС / СС / РУС-ЛАТ.
   *
   * Матрица 8x8 = 64 позиции, что в точности совпадает с диапазоном КОИ-7
   * 0x20..0x5F, поэтому таблица задана просто как коды по возрастанию:
   * code = 0x20 + row * 8 + col.
   *
   * ВНИМАНИЕ: это инженерное допущение, а не выписка из схемы. Реальная
   * разводка матрицы РК-86 может отличаться порядком строк/столбцов. Если
   * монитор из настоящего ПЗУ будет выдавать не те символы — правится ровно
   * здесь, одной таблицей, остальной код трогать не нужно.
   *
   * Управляющие клавиши (ВК, ПС, ЗБ, стрелки) на реальной машине получаются
   * как СС + буква, что и реализовано: Keyboard.pressCode() сам выставит
   * модификатор СС для кода < 0x20.
   */
  function buildAsciiMatrix() {
    const m = [];
    for (let row = 0; row < 8; row++) {
      const line = [];
      for (let col = 0; col < 8; col++) line.push(0x20 + row * 8 + col);
      m.push(line);
    }
    return m;
  }

  /* Раскладка браузерной клавиатуры -> код КОИ-7.
   * Ключ — event.code (не зависит от языка ввода в ОС, поэтому эмулятор
   * работает одинаково при русской и английской раскладке системы). */
  const DEFAULT_KEYMAP = {
    // Управляющие
    Enter: KEY.CR, NumpadEnter: KEY.CR,
    Backspace: KEY.RUB, Delete: KEY.RUB,
    Tab: KEY.TAB,
    ArrowLeft: KEY.LEFT, ArrowRight: KEY.RIGHT,
    ArrowUp: KEY.UP, ArrowDown: KEY.DOWN,
    Home: KEY.HOME,
    Escape: 0x1B,
    Space: 0x20,

    // Цифры (верхний ряд). Со сдвигом — символы над цифрами.
    Digit0: [0x30, 0x30], Digit1: [0x31, 0x21], Digit2: [0x32, 0x22],
    Digit3: [0x33, 0x23], Digit4: [0x34, 0x24], Digit5: [0x35, 0x25],
    Digit6: [0x36, 0x26], Digit7: [0x37, 0x27], Digit8: [0x38, 0x28],
    Digit9: [0x39, 0x29],

    // Знаки
    Minus: [0x2D, 0x3D], Equal: [0x3D, 0x2B],
    BracketLeft: [0x5B, 0x5B], BracketRight: [0x5D, 0x5D],
    Backslash: [0x5C, 0x5C], Semicolon: [0x3B, 0x3A],
    Quote: [0x27, 0x22], Comma: [0x2C, 0x3C],
    Period: [0x2E, 0x3E], Slash: [0x2F, 0x3F],
    Backquote: [0x40, 0x40]
  };
  // Латиница A..Z -> 0x41..0x5A
  for (let i = 0; i < 26; i++) {
    DEFAULT_KEYMAP['Key' + String.fromCharCode(65 + i)] = 0x41 + i;
  }

  /* ------------------------------------------------------------------------ */
  /*  Радио-86РК                                                              */
  /* ------------------------------------------------------------------------ */
  const RK86 = {
    id: 'rk86',
    name: 'Радио-86РК',

    cpuFreq: 1777777,      // КР580ВМ80А, ~1.78 МГц
    framesPerSecond: 50,

    // Карта памяти
    regions: [
      { name: 'ОЗУ',   start: 0x0000, end: 0x7FFF, type: 'ram' },
      { name: 'ВВ55-1', start: 0x8000, end: 0x9FFF, type: 'io', device: 'ppi1', mask: 0x03 },
      { name: 'ВВ55-2', start: 0xA000, end: 0xBFFF, type: 'io', device: 'ppi2', mask: 0x03 },
      { name: 'ВГ75',  start: 0xC000, end: 0xDFFF, type: 'io', device: 'crt',  mask: 0x01 },
      { name: 'ВИ53',  start: 0xE000, end: 0xEFFF, type: 'io', device: 'timer', mask: 0x03 },
      { name: 'ВТ57',  start: 0xF000, end: 0xF7FF, type: 'io', device: 'dma',  mask: 0x0F },
      { name: 'ПЗУ',   start: 0xF800, end: 0xFFFF, type: 'rom' }
    ],

    romStart: 0xF800,
    romSize: 0x0800,       // Монитор, 2 КБ

    // На реальной машине после сброса триггер подставляет ПЗУ на адрес 0000,
    // и первая же команда уводит управление в монитор. Эмулируем результат:
    // стартуем сразу с начала ПЗУ.
    resetVector: 0xF800,

    video: {
      base: 0x76D0,        // умолчание; если монитор запрограммирует ВТ57 —
                           // адрес возьмётся из канала 2 контроллера ПДП
      cols: 64,
      rows: 25,
      charWidth: 6,        // знакоместо 6x8, используются младшие 6 бит байта
      charHeight: 8,
      scale: 2,
      colorBg: '#101410',
      colorFg: '#37d63a',
      // Бит 7 кода символа — инверсия знакоместа
      inverseOnHighBit: true
    },

    charGen: {
      size: 0x0800,        // 2 КБ: 256 знаков по 8 байт
      bytesPerChar: 8,
      // Крайний левый пиксель — старший из используемых бит (бит 5 для 6x8)
      msbFirst: true
    },

    keyboard: {
      matrix: buildAsciiMatrix(),
      keymap: DEFAULT_KEYMAP,
      ppi: 'ppi1',
      // Биты модификаторов в порту C
      modShift: 0x01,      // УС
      modCtrl: 0x02,       // СС
      modRus: 0x04,        // РУС/ЛАТ

      /* Полярность сигналов. Значения по умолчанию — «активный уровень
       * низкий» по всем трём линиям, как обычно и делается на матричных
       * клавиатурах тех лет. Если монитор из настоящего ПЗУ не реагирует на
       * нажатия, эти флаги перебираются в панели «Клавиатура» прямо на ходу —
       * всего четыре сочетания, нужное видно сразу. */
      scanActiveLow: true,     // строка выбрана НУЛЁМ в порту A
      returnActiveLow: true,   // нажатая клавиша даёт НОЛЬ в порту B
      modActiveLow: true       // нажатый модификатор даёт НОЛЬ в порту C
    },

    charsetCyrillic: KOI7_CYRILLIC
  };

  /* ------------------------------------------------------------------------ */
  /*  Микроша                                                                 */
  /*  Клон РК-86: та же архитектура, отличается ПЗУ и мелочами ввода/вывода.  */
  /*  Значения ниже — копия РК-86; при появлении точных данных правятся здесь. */
  /* ------------------------------------------------------------------------ */
  const MIKROSHA = JSON.parse(JSON.stringify({
    ...RK86, id: 'mikrosha', name: 'Микроша', keyboard: null, charsetCyrillic: null
  }));
  MIKROSHA.keyboard = RK86.keyboard;
  MIKROSHA.charsetCyrillic = KOI7_CYRILLIC;

  /* ------------------------------------------------------------------------ */
  /*  Апогей БК-01                                                            */
  /*  Больше ОЗУ и другой адрес экрана. Карта уточняется по мере проверки.     */
  /* ------------------------------------------------------------------------ */
  const APOGEY = JSON.parse(JSON.stringify({
    ...RK86, id: 'apogey', name: 'Апогей БК-01', keyboard: null, charsetCyrillic: null
  }));
  APOGEY.keyboard = RK86.keyboard;
  APOGEY.charsetCyrillic = KOI7_CYRILLIC;
  APOGEY.video.base = 0xEB00;
  APOGEY.video.colorFg = '#d8d8d8';

  global.MACHINES = { rk86: RK86, mikrosha: MIKROSHA, apogey: APOGEY };
  global.KOI7_CYRILLIC = KOI7_CYRILLIC;
  global.RK_KEYS = KEY;

})(window);
